package main

import (
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/k0sproject/k0s/pkg/apis/k0s/v1beta1"
)

type componentDocumentation struct {
	upgrade     string
	replacement string
	breakage    string
}

var componentDocumentationByName = map[string]componentDocumentation{
	v1beta1.LiquidComponentCilium: {
		upgrade:     "Change `spec.liquid.components.cilium.version`.",
		replacement: "Install another CNI, then set `replacement: external`.",
		breakage:    "Replacing it without a compatible CNI interrupts pod networking and removes liquid's Gateway API implementation.",
	},
	v1beta1.LiquidComponentGatewayAPI: {
		upgrade:     "Change `spec.liquid.components.gatewayAPI.version`.",
		replacement: "Install compatible Gateway API CRDs, then set `replacement: external`.",
		breakage:    "Removing or downgrading CRDs can make Gateway API objects invalid or unavailable to Cilium.",
	},
	v1beta1.LiquidComponentLocalPath: {
		upgrade:     "Change `spec.liquid.components.localPath.version`.",
		replacement: "Install another local provisioner, migrate claims, then set `replacement: external`.",
		breakage:    "Existing volumes remain tied to their nodes and are not migrated automatically.",
	},
	v1beta1.LiquidComponentDistributedStorage: {
		upgrade:     "Follow the Longhorn compatibility notes, then change `spec.liquid.components.distributedStorage.version`.",
		replacement: "Migrate volumes to an external CSI provider; Rook-Ceph is the documented path for larger estates.",
		breakage:    "Replacing it without migrating volumes makes Longhorn-backed claims, snapshots, and backups unavailable.",
	},
}

func main() {
	output := flag.String("output", "docs/liquid/components.md", "generated documentation path")
	flag.Parse()

	content, err := renderComponentsPage()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*output, []byte(content), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func renderComponentsPage() (string, error) {
	components := v1beta1.DefaultLiquidSpec().Components
	var page strings.Builder
	page.WriteString("<!--\n")
	page.WriteString("SPDX-FileCopyrightText: 2026 k0s authors\n")
	page.WriteString("SPDX-License-Identifier: CC-BY-SA-4.0\n")
	page.WriteString("-->\n\n")
	page.WriteString("# Liquid components\n\n")
	page.WriteString("New liquid clusters declare four replaceable components in `spec.liquid.components`. ")
	page.WriteString("The declarations persist in the cluster configuration, so upgrading the k0s binary does not select new component versions.\n\n")
	page.WriteString("<!-- Generated by go run ./hack/gen-components-table. Do not edit by hand. -->\n\n")
	page.WriteString("| Component | Default version | Chart source | Upgrade path | Replacement path | What breaks when replaced |\n")
	page.WriteString("|---|---:|---|---|---|---|\n")
	for _, entry := range components.Entries() {
		documentation, ok := componentDocumentationByName[entry.Name]
		if !ok {
			return "", fmt.Errorf("component %q has no documentation", entry.Name)
		}
		fmt.Fprintf(
			&page,
			"| `%s` | `%s` | [%s](%s) | %s | %s | %s |\n",
			entry.Name,
			entry.Component.Version,
			entry.Component.Chart.Name,
			entry.Component.Chart.Repository,
			documentation.upgrade,
			documentation.replacement,
			documentation.breakage,
		)
	}
	page.WriteString("\n## Version changes\n\n")
	page.WriteString("Edit the component's `version` in the `ClusterConfig` named `k0s` in `kube-system`. ")
	page.WriteString("The extensions controller updates only that component's `Chart` resource. ")
	page.WriteString("Managed objects are named `liquid-cilium`, `liquid-gateway-api`, `liquid-local-path`, and `liquid-distributed-storage` in `kube-system`. ")
	page.WriteString("Wait for `k0s liquid components` to show the same declared and deployed versions before continuing. ")
	page.WriteString("Keep the previous declaration available for rollback and follow the component's own version-skew and data-migration guidance.\n\n")
	page.WriteString("Defaults are creation-time input. `k0s config create` emits all declarations, and the first controller persists them. ")
	page.WriteString("Reading an older configuration that has no `spec.liquid` does not add components. ")
	page.WriteString("A later k0s binary therefore cannot replace a stored component version with its newer compiled default.\n\n")
	page.WriteString("## External replacements\n\n")
	page.WriteString("Set `replacement: external` only after the replacement is installed and its workloads are healthy. ")
	page.WriteString("k0s then creates no `Chart`, stops managing a previously managed release without uninstalling it, and does not remove external resources. ")
	page.WriteString("Setting `enabled: false` on a managed component is different: k0s removes its managed `Chart` and uninstalls that release.\n\n")
	page.WriteString("Cilium is the Gateway API controller; the `gatewayAPI` component supplies CRDs only. ")
	page.WriteString("The Gateway API project does not yet publish a CRD Helm chart, so the default uses Wiremind's verified packaging of the upstream CRDs. ")
	page.WriteString("Rancher's local-path provisioner also lacks a project-operated chart repository, so the default uses Containeroo's verified packaging. ")
	page.WriteString("Both sources are explicit in the configuration and can be replaced.\n\n")
	page.WriteString("Longhorn requires iSCSI initiator packages and services on every storage node. ")
	page.WriteString("The local-path class is the default; Longhorn remains opt-in per claim unless the operator changes the chart values.\n\n")
	page.WriteString("The bootloose integration test starts a dynamically configured controller and joins two workers. It prepares Cilium's bpffs, cgroup v2, and network-namespace mounts, and its image enables `iscsid` so the default Longhorn release is exercised with the same host prerequisite.\n")
	page.WriteString("\n## Inspect versions\n\n")
	page.WriteString("Run `k0s liquid components` on a controller to compare every declared version with the Helm release version recorded on its `Chart`. ")
	page.WriteString("A managed row is complete when its status is `deployed` and both versions match. External rows report `external` because k0s does not inspect or control the provider's release.\n")

	return page.String(), nil
}
